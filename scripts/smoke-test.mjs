import assert from 'node:assert/strict';
import { cloneSample } from '../src/samples.js';
import { runAlgorithm, allRoutesFrom } from '../src/algorithms.js';
const graph = cloneSample('Small network');
const d = runAlgorithm('Dijkstra', graph.nodes, graph.edges, 'PC-A', 'S1');
assert.equal(d.error, '');
assert.equal(d.cost, 10);
assert.deepEqual(d.path, ['PC-A', 'R2', 'R1', 'R3', 'S1']);
const b = runAlgorithm('BFS', graph.nodes, graph.edges, 'PC-A', 'S1');
assert.equal(b.error, '');
assert.equal(b.hops, 3);
const down = graph.edges.find(e => e.id === 'e2');
down.status = 'down';
const reroute = runAlgorithm('Dijkstra', graph.nodes, graph.edges, 'PC-A', 'S1');
assert.equal(reroute.error, '');
assert.equal(reroute.path.includes('R2'), false);
const tables = allRoutesFrom(graph.nodes, graph.edges, 'PC-A');
assert.equal(tables.find(r => r.destination === 'S1').status, 'Reachable');
console.log('NetRoute smoke tests passed: Dijkstra, BFS, link failure reroute, routing table.');
